long long countCommas(long long n) {
    if (n<1000)
    {
        return 0;
    }
    long long ans=0;
    if (n>999 && n<1000000)
    {
        ans=n-999;
    }
    else if (n>999999 && n<1000000000)
    {
        ans=(n-999999)*2 + 999000;
    }
    else if (n>999999999 && n<1000000000000)
    {
        ans=(n-999999999)*3 + 999000000*2 + 999000;
    }
    else if (n>999999999999 && n<1000000000000000)
    {
        ans=(n-999999999999)*4 + 999000000000*3 + 999000000*2 + 999000;
    }
    else 
    {
        ans= 5 + 999000000000000*4 + 999000000000*3 + 999000000*2 + 999000;
    }
    return ans;
}